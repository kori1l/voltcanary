CREATE TABLE device_variables (
    id UUID PRIMARY KEY,
    account_id UUID NOT NULL REFERENCES accounts(id),
    device_type VARCHAR(64) NOT NULL,
    variable_key VARCHAR(64) NOT NULL,
    label VARCHAR(80) NOT NULL,
    origin VARCHAR(16) NOT NULL,
    unit VARCHAR(24) NOT NULL,
    version INTEGER NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    default_revision INTEGER,
    created_by UUID NOT NULL,
    updated_by UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(account_id, device_type, variable_key)
);
CREATE TABLE device_variable_revisions (
    variable_id UUID NOT NULL REFERENCES device_variables(id),
    revision INTEGER NOT NULL,
    state VARCHAR(16) NOT NULL,
    contract_json TEXT NOT NULL,
    digest VARCHAR(64) NOT NULL,
    created_by UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_by UUID,
    published_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(variable_id, revision)
);
CREATE TABLE source_variable_bindings (
    data_source_id UUID NOT NULL REFERENCES data_sources(id),
    variable_id UUID NOT NULL REFERENCES device_variables(id),
    revision INTEGER NOT NULL,
    version INTEGER NOT NULL,
    input_paths_json TEXT NOT NULL,
    enabled BOOLEAN NOT NULL,
    inherited BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by UUID NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(data_source_id, variable_id),
    FOREIGN KEY(variable_id, revision) REFERENCES device_variable_revisions(variable_id, revision)
);
CREATE TABLE source_processing_bundles (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source_id UUID NOT NULL REFERENCES data_sources(id),
    generation BIGINT NOT NULL,
    account_id UUID NOT NULL REFERENCES accounts(id),
    device_id UUID NOT NULL REFERENCES devices(id),
    digest VARCHAR(64) NOT NULL,
    bundle_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(data_source_id, generation)
);
CREATE TABLE variable_rollout_targets (
    id UUID PRIMARY KEY,
    variable_id UUID NOT NULL REFERENCES device_variables(id),
    revision INTEGER NOT NULL,
    data_source_id UUID NOT NULL REFERENCES data_sources(id),
    input_paths_json TEXT NOT NULL,
    enabled BOOLEAN NOT NULL,
    status VARCHAR(16) NOT NULL,
    expected_binding_version INTEGER NOT NULL DEFAULT 0,
    diagnostic VARCHAR(200),
    created_by UUID NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_variable_account_type ON device_variables(account_id, device_type);
CREATE INDEX idx_variable_binding_definition ON source_variable_bindings(variable_id, enabled);
CREATE INDEX idx_variable_rollout_status ON variable_rollout_targets(status, updated_at);
CREATE TABLE device_variable_default_bindings (
    variable_id UUID PRIMARY KEY REFERENCES device_variables(id),
    source_type VARCHAR(32) NOT NULL,
    input_paths_json TEXT NOT NULL,
    created_by UUID NOT NULL,
    device_cursor VARCHAR(36) NOT NULL DEFAULT ''
);
